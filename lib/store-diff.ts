import type { Activity, PlatformStore } from "./platform-types";

export const SAVED_KEYS = ["tickets", "orders", "tasks", "machines", "profitability"] as const;
export type SavedKey = (typeof SAVED_KEYS)[number];
type SavedEntity = Exclude<PlatformStore[SavedKey][number], Activity>;

export type StoreChange = { key: SavedKey; entity: SavedEntity; action: "created" | "updated" | "deleted" };

const stamp = (entity: object) => (entity as { updatedAt?: string }).updatedAt || "";

/**
 * Deleting through a save is limited to what the app deletes on purpose: an
 * automatic filter task that is no longer needed. Everything else is deleted
 * by its own action, never because it is missing from a screen.
 */
const deletableBySave = (key: SavedKey, entity: SavedEntity) =>
  key === "tasks"
  && (entity as { autoGenerated?: boolean }).autoGenerated === true
  && (entity as { type?: string }).type === "תחזוקת פילטר";

/**
 * What a save should write: the difference between what the screen holds now
 * and what the database last sent.
 *
 * A save waits in a queue, so by the time it runs the database may have sent
 * something newer, for example from another open window. Comparing an older
 * screen to that newer data used to delete what the other window added and
 * re-create what it deleted, back and forth (tens of thousands of writes on
 * 12.10). So a save:
 * - never deletes, except an automatic filter task the app removes on purpose;
 * - never re-creates something the database already had and has since removed;
 * - never overwrites a newer version with an older one (by `updatedAt`).
 */
export function changedEntities(
  next: PlatformStore,
  synced: PlatformStore | null,
  seenBefore: ReadonlySet<string> = new Set(),
): StoreChange[] {
  const changes: StoreChange[] = [];
  for (const key of SAVED_KEYS) {
    const before = new Map((synced?.[key] || []).map((entity) => [entity.id, entity as SavedEntity]));
    for (const entity of next[key] as SavedEntity[]) {
      const current = before.get(entity.id);
      before.delete(entity.id);
      if (!current) {
        if (!seenBefore.has(`${key}:${entity.id}`)) changes.push({ key, entity, action: "created" });
        continue;
      }
      if (JSON.stringify(current) === JSON.stringify(entity)) continue;
      if (stamp(entity) && stamp(current) && stamp(entity) < stamp(current)) continue;
      changes.push({ key, entity, action: "updated" });
    }
    for (const entity of before.values()) {
      if (deletableBySave(key, entity)) changes.push({ key, entity, action: "deleted" });
    }
  }
  return changes;
}

/** Every entity a snapshot contains, as "key:id", to remember what the database has held. */
export const entityKeysOf = (store: PlatformStore) =>
  SAVED_KEYS.flatMap((key) => (store[key] as SavedEntity[]).map((entity) => `${key}:${entity.id}`));
