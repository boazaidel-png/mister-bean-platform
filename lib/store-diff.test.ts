import assert from "node:assert/strict";
import test from "node:test";
import { changedEntities, entityKeysOf } from "./store-diff.ts";
import type { Machine, PlatformStore, Task } from "./platform-types.ts";

const store = (extra: Partial<PlatformStore> = {}): PlatformStore => ({ tickets: [], orders: [], tasks: [], machines: [], activities: [], profitability: [], ...extra });
const machine = (id: string, extra: Partial<Machine> = {}) => ({ id, accountId: "a", site: "", model: "Jura", serial: "1", status: "פעילה", commercial: "", location: "", lastService: "", nextService: "", updatedAt: "2026-10-12T10:00:00Z", ...extra }) as Machine;

test("a stale screen does not delete what another window added", () => {
  const synced = store({ machines: [machine("m1"), machine("m2")] });
  const staleScreen = store({ machines: [machine("m1")] });
  assert.deepEqual(changedEntities(staleScreen, synced), []);
});

test("a stale screen does not bring back what was deleted elsewhere", () => {
  const seen = new Set(entityKeysOf(store({ machines: [machine("m1"), machine("m2")] })));
  const synced = store({ machines: [machine("m1")] });
  const staleScreen = store({ machines: [machine("m1"), machine("m2")] });
  assert.deepEqual(changedEntities(staleScreen, synced, seen), []);
});

test("new things and real edits are still saved, older versions are not", () => {
  const synced = store({ machines: [machine("m1")] });
  const edited = store({ machines: [machine("m1", { status: "מושבתת", updatedAt: "2026-10-12T11:00:00Z" }), machine("m3")] });
  assert.deepEqual(changedEntities(edited, synced).map((change) => [change.entity.id, change.action]), [["m1", "updated"], ["m3", "created"]]);
  const older = store({ machines: [machine("m1", { status: "מושבתת", updatedAt: "2026-10-12T09:00:00Z" })] });
  assert.deepEqual(changedEntities(older, synced), []);
});

test("only an automatic filter task the app drops is deleted by a save", () => {
  const filterTask = { id: "t1", accountId: "a", title: "", type: "תחזוקת פילטר", dueDate: "", priority: "", status: "פתוחה", autoGenerated: true } as Task;
  const manualTask = { ...filterTask, id: "t2", autoGenerated: false };
  const changes = changedEntities(store(), store({ tasks: [filterTask, manualTask] }));
  assert.deepEqual(changes.map((change) => [change.entity.id, change.action]), [["t1", "deleted"]]);
});
