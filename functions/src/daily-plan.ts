import { reconcileFilterReplacementTask } from "../../lib/maintenance-engine";
import { contractMonthlyKg, syncContractOrders } from "../../lib/order-sync";
import type { Customer, Machine, Order, Task } from "../../lib/platform-types";
import { addDays, daysBetween, formatShortDate } from "./dates";

/** The month's order opens this many days before its delivery. */
export const ORDER_OPEN_DAYS = 14;
/** The customer is asked to confirm this many days before delivery, and once more near the end. */
export const ORDER_REMINDER_DAYS = 10;
export const ORDER_FINAL_REMINDER_DAYS = 3;
/** The office gets a task to prepare the order this many days before delivery. */
export const ORDER_PREP_DAYS = 4;
/** Periodic machine service gets a task this many days ahead. */
export const SERVICE_TASK_NOTICE_DAYS = 14;

const CLOSED_ORDER = ["סופק", "בוטל"];
const AWAITING_CUSTOMER = ["לפי חוזה", "ממתין לעדכון לקוח"];
const OFFICE = "מנהל המערכת";

const safeKey = (value: string) => value.replace(/[^a-zA-Z0-9_-]/g, "-");
const addMonth = (month: string) => {
  const [year, value] = month.split("-").map(Number);
  return value === 12 ? `${year + 1}-01` : `${year}-${String(value + 1).padStart(2, "0")}`;
};
/** The customer's delivery date in a month (days after the 28th fall on the 28th). */
export const deliveryDate = (customer: Pick<Customer, "deliveryDayOfMonth">, month: string) =>
  `${month}-${String(Math.min(28, Math.max(1, customer.deliveryDayOfMonth || 1))).padStart(2, "0")}`;

/**
 * The next delivery still ahead of the customer: this month's, unless its
 * date has passed or its order is already delivered or cancelled.
 */
export function upcomingDelivery(customer: Customer, orders: Order[], today: string) {
  const thisMonth = today.slice(0, 7);
  for (const month of [thisMonth, addMonth(thisMonth)]) {
    const date = deliveryDate(customer, month);
    const order = orders.find((item) => item.accountId === customer.id && item.month === month);
    if (date >= today && !CLOSED_ORDER.includes(order?.status || "")) return { month, date, order };
  }
  const month = addMonth(addMonth(thisMonth));
  return { month, date: deliveryDate(customer, month), order: undefined };
}

type Plan = {
  newOrders: Order[];
  newTasks: Task[];
  reminders: Array<{ order: Order; customer: Customer; date: string; stage: "first" | "final" }>;
};

/**
 * Decides what today's run creates. Pure, so it can be tested: opens the
 * order for each customer's next delivery, picks the customers to remind,
 * and adds tasks to prepare orders, replace filters and service machines.
 * Existing documents are never changed; ids match the ones the site uses,
 * so the site and this job never create the same thing twice.
 */
export function planDailyRun(input: {
  customers: Customer[];
  orders: Order[];
  tasks: Task[];
  machines: Machine[];
  today: string;
  now: string;
}): Plan {
  const { customers, today, now } = input;
  const plan: Plan = { newOrders: [], newTasks: [], reminders: [] };
  const taskIds = new Set(input.tasks.map((task) => task.id));
  const automationKeys = new Set(input.tasks.map((task) => task.automationKey).filter(Boolean));
  const addTask = (task: Task) => {
    if (taskIds.has(task.id) || (task.automationKey && automationKeys.has(task.automationKey))) return;
    taskIds.add(task.id);
    if (task.automationKey) automationKeys.add(task.automationKey);
    plan.newTasks.push(task);
  };

  for (const customer of customers) {
    if (customer.status === "בהשהיה" || contractMonthlyKg(customer, customer.commercialAgreement) <= 0) continue;
    const ownOrders = input.orders.filter((order) => order.accountId === customer.id);
    const { month, date, order: existing } = upcomingDelivery(customer, ownOrders, today);
    const days = daysBetween(today, date);
    if (days > ORDER_OPEN_DAYS) continue;

    let order = existing;
    if (!order) {
      order = syncContractOrders(ownOrders, [customer], month, undefined, now).find((item) => item.month === month);
      if (!order) continue;
      plan.newOrders.push(order);
    }

    if (!order.customerConfirmedAt && AWAITING_CUSTOMER.includes(order.status) && days <= ORDER_REMINDER_DAYS) {
      plan.reminders.push({ order, customer, date, stage: days <= ORDER_FINAL_REMINDER_DAYS ? "final" : "first" });
    }

    if (days <= ORDER_PREP_DAYS && order.status !== "בוטל") {
      const kg = Math.round(order.approvedKg || order.requestedKg);
      addTask({
        id: `task-order-prep-${safeKey(order.id)}`,
        accountId: customer.id,
        automationKey: `order-prep:${order.id}`,
        autoGenerated: true,
        title: `הכנת הזמנה · ${customer.name} · ${kg} ק״ג · ${order.blend} · אספקה ${formatShortDate(date)}`,
        type: "הכנת הזמנה",
        dueDate: addDays(date, -1) < today ? today : addDays(date, -1),
        priority: "גבוהה",
        status: "פתוחה",
        assignedTo: customer.owner || OFFICE,
        createdAt: now,
        updatedAt: now,
      });
    }
  }

  const ownerByAccount = new Map(customers.map((customer) => [customer.id, customer.owner || OFFICE]));
  const todayDate = new Date(`${today}T12:00:00`);
  for (const machine of input.machines) {
    if (machine.status === "הוחזרה") continue;
    const owner = ownerByAccount.get(machine.accountId) || OFFICE;
    const machineTasks = input.tasks.filter((task) => task.machineId === machine.id);
    for (const task of reconcileFilterReplacementTask(machineTasks, machine, owner, todayDate)) {
      if (task.createdAt === todayDate.toISOString()) addTask({ ...task, createdAt: now, updatedAt: now });
    }

    const serviceDate = machine.nextService?.slice(0, 10) || "";
    if (/^\d{4}-\d{2}-\d{2}$/.test(serviceDate) && daysBetween(today, serviceDate) <= SERVICE_TASK_NOTICE_DAYS) {
      const where = [machine.site, machine.floor, machine.location].filter(Boolean).join(" · ");
      addTask({
        id: `task-service-${safeKey(machine.id)}-${serviceDate}`,
        accountId: machine.accountId,
        machineId: machine.id,
        automationKey: `service:${machine.id}:${serviceDate}`,
        autoGenerated: true,
        title: `טיפול תקופתי · ${machine.model}${where ? ` · ${where}` : ""}`,
        type: "טיפול תקופתי",
        dueDate: serviceDate,
        priority: "רגילה",
        status: "פתוחה",
        assignedTo: owner,
        createdAt: now,
        updatedAt: now,
      });
    }
  }
  return plan;
}
